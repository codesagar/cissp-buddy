const currentSourceStatus = [...releaseSourceHashes].map(
  ([contentId, hash]) => {
    const unitSource = path.join(
      webRoot,
      'lib/data/teaching',
      `${contentId}.json`,
    );
    const connectionSource = path.join(
      webRoot,
      'lib/data/connections',
      `${contentId}.json`,
    );
    const sourcePath = fs.existsSync(unitSource)
      ? unitSource
      : fs.existsSync(connectionSource)
        ? connectionSource
        : null;
    const currentSha256 = sourcePath
      ? sha256(fs.readFileSync(sourcePath))
      : null;
    return {
      contentId,
      sourcePath: sourcePath ? relativeToRepository(sourcePath) : null,
      releaseSha256: hash,
      currentSha256,
      matchesRelease: currentSha256 === hash,
    };
  },
);

