import { createHash } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const webRoot = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  '..',
);
const repositoryRoot = path.dirname(webRoot);
const courseRoot = path.join(webRoot, 'lib/data/course');
const reviewRoot = path.join(
  repositoryRoot,
  'planning/visual-learning-production/reviews',
);
const expectedRelease = process.argv
  .find((argument) => argument.startsWith('--expected-release='))
  ?.slice('--expected-release='.length);
const requestedOutput = process.argv
  .find((argument) => argument.startsWith('--output='))
  ?.slice('--output='.length);
const checkOnly = process.argv.includes('--check');

if (
  !expectedRelease ||
  !/^cissp-course-2026-09-[a-f0-9]{16}$/.test(expectedRelease)
)
  throw new Error('Pass --expected-release=cissp-course-2026-09-<16 hex>.');

const readJson = (file) => JSON.parse(fs.readFileSync(file, 'utf8'));
const sha256 = (value) => createHash('sha256').update(value).digest('hex');
const stable = (value) => {
  if (Array.isArray(value)) return value.map(stable);
  if (value && typeof value === 'object')
    return Object.fromEntries(
      Object.keys(value)
        .sort()
        .map((key) => [key, stable(value[key])]),
    );
  return value;
};
const stableJson = (value) => `${JSON.stringify(stable(value), null, 2)}\n`;
const relativeToRepository = (file) =>
  path.relative(repositoryRoot, file).split(path.sep).join('/');
const unitLink = (unitId, conceptId) =>
  `#/unit/${unitId}/understand${conceptId ? `/${conceptId}` : ''}`;

const manifest = readJson(path.join(courseRoot, 'manifest.json'));
if (manifest.releaseId !== expectedRelease)
  throw new Error(
    `Expected ${expectedRelease}, but generated bytes are ${manifest.releaseId}.`,
  );

const units = manifest.units.map((summary) =>
  readJson(path.join(courseRoot, 'units', `${summary.id}.json`)),
);
const connectionsIndex = readJson(
  path.join(courseRoot, 'connections-index.json'),
);
const connections = connectionsIndex.cases.map((summary) =>
  readJson(path.join(courseRoot, 'connections', `${summary.id}.json`)),
);
const sourceBindingDocument = readJson(
  path.join(courseRoot, 'source-bindings.json'),
);
const dispositionLedger = readJson(
  path.join(
    repositoryRoot,
    'planning/visual-learning-fresh-review/disposition-ledger.json',
  ),
);

for (const [label, releaseId] of [
  ['source bindings', sourceBindingDocument.releaseId],
  ['connections index', connectionsIndex.releaseId],
  ...units.map((unit) => [`unit ${unit.id}`, unit.releaseId]),
  ...connections.map((connection) => [
    `connection ${connection.id}`,
    connection.releaseId,
  ]),
])
  if (releaseId !== expectedRelease)
    throw new Error(
      `${label} belongs to ${releaseId}, not ${expectedRelease}.`,
    );

const requireCount = (actual, expected, label) => {
  if (actual !== expected)
    throw new Error(`Expected ${expected} ${label}; found ${actual}.`);
};
requireCount(units.length, 90, 'units');
requireCount(connections.length, 11, 'connection cases');
requireCount(
  connectionsIndex.referenceRelationships.length,
  21,
  'reference relationships',
);
requireCount(
  sourceBindingDocument.occurrences.length,
  892,
  'concept occurrence bindings',
);
requireCount(
  sourceBindingDocument.assessments.length,
  303,
  'assessment bindings',
);

const unitById = new Map(units.map((unit) => [unit.id, unit]));
const occurrenceBindingByKey = new Map();
for (const binding of sourceBindingDocument.occurrences) {
  const key = `${binding.unitId}::${binding.conceptId}`;
  if (occurrenceBindingByKey.has(key))
    throw new Error(`Duplicate concept occurrence binding ${key}.`);
  occurrenceBindingByKey.set(key, binding);
}

const conceptOccurrences = units.flatMap((unit) =>
  unit.concepts.map((concept) => {
    const binding = occurrenceBindingByKey.get(`${unit.id}::${concept.id}`);
    if (!binding)
      throw new Error(`Missing source binding for ${unit.id}/${concept.id}.`);
    for (const field of ['definition', 'decision', 'failureExample'])
      if (
        typeof concept[field] !== 'string' ||
        concept[field].trim().length < 16
      )
        throw new Error(`${unit.id}/${concept.id} lacks substantive ${field}.`);
    if (
      concept.sourceVisualId !== binding.sourceVisualId ||
      !concept.sourceRefIds.length
    )
      throw new Error(
        `${unit.id}/${concept.id} has inconsistent source mapping.`,
      );
    return {
      unitId: unit.id,
      conceptId: concept.id,
      label: concept.label,
      deepLink: unitLink(unit.id, concept.id),
      explanation: {
        definition: concept.definition,
        decision: concept.decision,
        failureExample: concept.failureExample,
      },
      source: {
        sourceVisualId: binding.sourceVisualId,
        sourceVisualPath: binding.sourceVisualPath,
        sourceVisualSha256: binding.sourceVisualHash,
        sourceRefIds: binding.sourceRefIds,
        bindingKind: binding.bindingKind,
        derivedFields: binding.derivedFields,
      },
    };
  }),
);
requireCount(conceptOccurrences.length, 892, 'resolved concept occurrences');

const conceptsById = new Map();
for (const occurrence of conceptOccurrences) {
  const current = conceptsById.get(occurrence.conceptId) || {
    conceptId: occurrence.conceptId,
    label: occurrence.label,
    occurrences: [],
  };
  current.occurrences.push({
    unitId: occurrence.unitId,
    deepLink: occurrence.deepLink,
  });
  conceptsById.set(occurrence.conceptId, current);
}
requireCount(conceptsById.size, 698, 'distinct concepts');

const models = [
  ...units.map((unit) => ({
    contentKind: 'unit',
    contentId: unit.id,
    deepLink: unitLink(unit.id),
    model: unit.teaching,
  })),
  ...connections.map((connection) => ({
    contentKind: 'connection',
    contentId: connection.id,
    deepLink: unitLink(connection.id),
    model: connection.model,
  })),
];
if (models.some((entry) => !entry.model))
  throw new Error(
    'Every production unit and connection must have a teaching model.',
  );
requireCount(models.length, 101, 'authored teaching models');

const assessmentBindingByProductionId = new Map(
  sourceBindingDocument.assessments.map((binding) => [
    binding.productionId,
    binding,
  ]),
);
const assessmentRows = models.flatMap((entry) =>
  ['prediction', 'transfer', 'retry'].map((phase) => {
    const check = entry.model[phase];
    const binding = assessmentBindingByProductionId.get(check.id);
    if (
      !binding ||
      binding.contentKind !== entry.contentKind ||
      binding.contentId !== entry.contentId ||
      binding.phase !== phase
    )
      throw new Error(
        `Assessment binding mismatch for ${entry.contentId}/${phase}.`,
      );
    if (!check.id.endsWith(`-${binding.authoredCheckHash.slice(0, 12)}`))
      throw new Error(`Assessment ${check.id} lacks its semantic hash suffix.`);
    return {
      contentKind: entry.contentKind,
      contentId: entry.contentId,
      phase,
      authoredId: binding.authoredId,
      productionId: binding.productionId,
      authoredCheckSha256: binding.authoredCheckHash,
      conceptIds: check.conceptIds,
      deepLink: entry.deepLink,
    };
  }),
);
requireCount(assessmentRows.length, 303, 'production assessments');

const assessmentScope = (contentKind) => {
  const rows = assessmentRows.filter((row) => row.contentKind === contentKind);
  const byPhase = Object.fromEntries(
    ['prediction', 'transfer', 'retry'].map((phase) => {
      const phaseRows = rows.filter((row) => row.phase === phase);
      return [
        phase,
        {
          checks: phaseRows.length,
          conceptScopeOccurrences: phaseRows.reduce(
            (sum, row) => sum + row.conceptIds.length,
            0,
          ),
          distinctConceptIds: new Set(
            phaseRows.flatMap((row) => row.conceptIds),
          ).size,
        },
      ];
    }),
  );
  return {
    checks: rows.length,
    conceptScopeOccurrences: rows.reduce(
      (sum, row) => sum + row.conceptIds.length,
      0,
    ),
    distinctConceptIds: new Set(rows.flatMap((row) => row.conceptIds)).size,
    byPhase,
    rows,
  };
};
const unitAssessments = assessmentScope('unit');
const connectionAssessments = assessmentScope('connection');
requireCount(unitAssessments.checks, 270, 'unit assessments');
requireCount(connectionAssessments.checks, 33, 'connection assessments');

const increment = (record, key, count = 1) => {
  record[key] = (record[key] || 0) + count;
};
const representations = {};
const representationsByContentKind = { unit: {}, connection: {} };
const rendererFamilies = {
  'relationship-map': 0,
  sequence: 0,
  comparison: 0,
  'recovery-timeline': 0,
};
let baseStateInstances = 0;
let variantCases = 0;
let variantStateInstances = 0;
for (const entry of models) {
  increment(representations, entry.model.representation);
  increment(
    representationsByContentKind[entry.contentKind],
    entry.model.representation,
  );
  baseStateInstances += entry.model.states.length;
  variantCases += entry.model.variants?.length || 0;
  variantStateInstances += (entry.model.variants || []).reduce(
    (sum, variant) => sum + variant.states.length,
    0,
  );
  const family = entry.model.quantitative
    ? 'recovery-timeline'
    : entry.model.representation === 'sequence'
      ? 'sequence'
      : entry.model.representation === 'comparison'
        ? 'comparison'
        : 'relationship-map';
  increment(rendererFamilies, family);
}

const productionTreatmentMappings = units.flatMap((unit) =>
  unit.teaching.treatmentDispositions.map((disposition) => ({
    unitId: unit.id,
    ...disposition,
  })),
);
const mappingsByTreatmentId = new Map();
for (const mapping of productionTreatmentMappings) {
  const current = mappingsByTreatmentId.get(mapping.treatmentId) || [];
  current.push(mapping);
  mappingsByTreatmentId.set(mapping.treatmentId, current);
}
const adjudicatedTreatmentIds = new Set(
  dispositionLedger.treatments.map((treatment) => treatment.id),
);
requireCount(
  adjudicatedTreatmentIds.size,
  79,
  'adjudicated treatment decisions',
);
const treatmentDecisions = dispositionLedger.treatments.map((treatment) => {
  const mappings = mappingsByTreatmentId.get(treatment.id) || [];
  if (!mappings.length)
    throw new Error(
      `Adjudicated treatment ${treatment.id} has no production mapping.`,
    );
  if (mappings.some((mapping) => !mapping.rationale?.trim()))
    throw new Error(
      `Treatment ${treatment.id} has an empty production rationale.`,
    );
  return {
    treatmentId: treatment.id,
    title: treatment.title || treatment.teachingQuestion,
    unitIds: treatment.unitIds,
    teachingQuestion: treatment.teachingQuestion,
    decisionForm:
      typeof treatment.form === 'string'
        ? treatment.form
        : treatment.form?.primary,
    decisionRationale:
      (typeof treatment.form === 'object' && treatment.form?.rationale) ||
      treatment.priorityReason,
    productionDispositions: mappings.map((mapping) => ({
      unitId: mapping.unitId,
      disposition: mapping.disposition,
      rationale: mapping.rationale,
      deepLink: unitLink(mapping.unitId),
    })),
    deepLinks: [
      ...new Set(mappings.map((mapping) => unitLink(mapping.unitId))),
    ],
  };
});
const supplementalTreatmentMappings = productionTreatmentMappings
  .filter((mapping) => !adjudicatedTreatmentIds.has(mapping.treatmentId))
  .map((mapping) => ({
    ...mapping,
    deepLink: unitLink(mapping.unitId),
    denominator:
      'supplemental prototype-equivalence mapping; not one of the 79 adjudicated treatments',
  }));

const releaseSourceHashes = new Map();
for (const binding of sourceBindingDocument.assessments) {
  const previous = releaseSourceHashes.get(binding.contentId);
  if (previous && previous !== binding.sourceTeachingHash)
    throw new Error(
      `${binding.contentId} has inconsistent source teaching hashes.`,
    );
  releaseSourceHashes.set(binding.contentId, binding.sourceTeachingHash);
}

const releaseIdsFromReview = (review) =>
  [
    review.releaseId,
    review.binding?.immutableReleaseId,
    review.binding?.releaseId,
    review.releaseBinding?.immutableReleaseId,
    review.releaseBinding?.releaseId,
    typeof review.releaseBinding === 'string' ? review.releaseBinding : null,
  ].filter(Boolean);
const decisionAccepted = (decision) => {
  const normalized = String(decision || '').toLowerCase();
  return (
    /(^|[_ -])(pass|passed|accepted|approved)($|[_ -])/.test(normalized) &&
    !/(pending|changes.required|rejected|fail)/.test(normalized)
  );
};
const reviewFiles = fs
  .readdirSync(reviewRoot)
  .filter((file) => file.endsWith('.json'))
  .sort();
const reviewEvidence = reviewFiles.map((file) => {
  const fullPath = path.join(reviewRoot, file);
  const review = readJson(fullPath);
  const reviewedHashes = review.scope?.modelHashes
    ? Object.entries(review.scope.modelHashes)
    : Array.isArray(review.cases)
      ? review.cases
          .filter((entry) => entry.unitId && entry.sha256)
          .map((entry) => [entry.unitId, entry.sha256])
      : [];
  const exactMatches = reviewedHashes.filter(
    ([id, hash]) => releaseSourceHashes.get(id) === hash,
  ).length;
  const mismatches = reviewedHashes
    .filter(([id, hash]) => releaseSourceHashes.get(id) !== hash)
    .map(([id, reviewedSha256]) => ({
      id,
      reviewedSha256,
      releaseSha256: releaseSourceHashes.get(id) || null,
    }));
  const decision = review.verdict || review.status || 'unclassified';
  const reviewedDomains = review.scope?.domains;
  const scopeGroup = Array.isArray(review.cases)
    ? 'connections'
    : Array.isArray(reviewedDomains) &&
        reviewedDomains.length > 0 &&
        reviewedDomains.every((domain) => [1, 2, 3, 4].includes(domain))
      ? 'domains-1-2-3-4'
      : Array.isArray(reviewedDomains) &&
          reviewedDomains.length > 0 &&
          reviewedDomains.every((domain) => [5, 6, 7, 8].includes(domain))
        ? 'domains-5-6-7-8'
        : 'unclassified';
  const exactSourceBinding =
    reviewedHashes.length > 0 && exactMatches === reviewedHashes.length;
  const sourceAccepted = exactSourceBinding && decisionAccepted(decision);
  const releaseBound = releaseIdsFromReview(review).includes(expectedRelease);
  return {
    path: relativeToRepository(fullPath),
    sha256: sha256(fs.readFileSync(fullPath)),
    reviewId: review.reviewId || null,
    reviewedAt: review.reviewedAt || null,
    scopeGroup,
    decision,
    decisionAccepted: decisionAccepted(decision),
    reviewedModelCount: reviewedHashes.length,
    exactModelHashMatches: exactMatches,
    matchingModelIds: reviewedHashes
      .filter(([id, hash]) => releaseSourceHashes.get(id) === hash)
      .map(([id]) => id),
    exactSourceBinding,
    sourceAccepted,
    releaseBound,
    releaseIdsNamedByReview: releaseIdsFromReview(review),
    releaseAcceptance: !exactSourceBinding
      ? 'source_bytes_do_not_match_release_or_are_unbound'
      : !sourceAccepted
        ? 'review_changes_required_or_acceptance_pending'
        : !releaseBound
          ? 'source_accepted_release_binding_pending'
          : 'accepted_for_exact_release',
    mismatches,
  };
});
const requiredReviewGroups = [
  'domains-1-2-3-4',
  'domains-5-6-7-8',
  'connections',
];
const requiredModelIdsByReviewGroup = {
  'domains-1-2-3-4': [...releaseSourceHashes.keys()].filter((id) =>
    /^d[1-4]-/.test(id),
  ),
  'domains-5-6-7-8': [...releaseSourceHashes.keys()].filter((id) =>
    /^d[5-8]-/.test(id),
  ),
  connections: [...releaseSourceHashes.keys()].filter((id) =>
    id.startsWith('cross-'),
  ),
};
const selectedReviews = requiredReviewGroups.map((scopeGroup) => {
  const acceptedReviews = reviewEvidence.filter(
    (review) => review.scopeGroup === scopeGroup && review.decisionAccepted,
  );
  const acceptedModelIds = new Set(
    acceptedReviews.flatMap((review) => review.matchingModelIds),
  );
  const requiredModelIds = requiredModelIdsByReviewGroup[scopeGroup];
  const uncoveredModelIds = requiredModelIds.filter(
    (id) => !acceptedModelIds.has(id),
  );
  const currentReleaseReviews = acceptedReviews.filter(
    (review) => review.releaseBound && review.exactSourceBinding,
  );
  const acceptedForExactRelease =
    uncoveredModelIds.length === 0 && currentReleaseReviews.length > 0;
  return {
    scopeGroup,
    releaseAcceptance: acceptedForExactRelease
      ? 'accepted_for_exact_release'
      : 'acceptance_pending_exact_final_review_and_release_bindings',
    requiredModelHashes: requiredModelIds.length,
    acceptedModelHashes: requiredModelIds.length - uncoveredModelIds.length,
    uncoveredModelIds,
    currentReleaseReviewPaths: currentReleaseReviews.map(
      (review) => review.path,
    ),
    supportingReviewPaths: acceptedReviews
      .filter((review) =>
        review.matchingModelIds.some((id) => requiredModelIds.includes(id)),
      )
      .map((review) => review.path),
  };
});
const allRequiredReviewsAccepted = selectedReviews.every(
  (review) => review.releaseAcceptance === 'accepted_for_exact_release',
);

