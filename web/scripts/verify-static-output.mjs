/** Exhaustive packaged-content and strict static-HTTP checks; browser visual QA is separate. */
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { fileURLToPath, pathToFileURL } from 'node:url';
import {
  validateCourseRelease,
  validateCourseConnections,
} from '../lib/course/validate.ts';
import { validateRelease } from '../lib/content/validate.ts';
import { releasePack } from '../lib/content/release-pack.ts';
import { startStaticServer, normalizeBase } from './static-server.mjs';

const webRoot = fileURLToPath(new URL('../', import.meta.url));
const sourceRoot = path.join(webRoot, 'lib/data/course');
const readJson = (file) => JSON.parse(fs.readFileSync(file, 'utf8'));
const hash = (bytes) => createHash('sha256').update(bytes).digest('hex');
const walk = (directory) =>
  fs.readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    assert.ok(
      !entry.isSymbolicLink(),
      `Published output must not contain symlinks: ${entry.name}`,
    );
    const file = path.join(directory, entry.name);
    return entry.isDirectory() ? walk(file) : [file];
  });
const escape = (value) =>
  value.replace(
    /[&<>"']/g,
    (character) =>
      ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[
        character
      ],
  );

export async function verifyStaticOutput({
  directory = path.join(webRoot, 'dist'),
  base = '/',
  expectedRelease,
  port = 0,
} = {}) {
  directory = path.resolve(directory);
  base = normalizeBase(base);
  const manifest = readJson(
    path.join(directory, 'content/course/manifest.json'),
  );
  const sourceManifest = readJson(path.join(sourceRoot, 'manifest.json'));
  assert.equal(
    manifest.releaseId,
    expectedRelease || sourceManifest.releaseId,
    'Packaged release matches requested release',
  );
  assert.deepEqual(
    manifest,
    sourceManifest,
    'Packaged manifest matches generated source',
  );
  const releasePath = `content/course/${manifest.releaseId}`;
  const unitPaths = manifest.units.map(
    ({ id }) => `${releasePath}/units/${id}.json`,
  );
  const units = unitPaths.map((file) => readJson(path.join(directory, file)));
  const indexPath = `${releasePath}/connections-index.json`;
  const index = readJson(path.join(directory, indexPath));
  const connectionPaths = index.cases.map(
    ({ id }) => `${releasePath}/connections/${id}.json`,
  );
  const connections = connectionPaths.map((file) =>
    readJson(path.join(directory, file)),
  );
  validateCourseRelease(manifest, units, true);
  validateCourseConnections(index, connections, units, true);
  const exactNames = (folder, expected) =>
    assert.deepEqual(
      fs.readdirSync(folder).sort(),
      expected.map((file) => path.basename(file)).sort(),
      `Complete, exact inventory: ${folder}`,
    );
  exactNames(path.join(directory, releasePath, 'units'), unitPaths);
  exactNames(path.join(directory, releasePath, 'connections'), connectionPaths);
  const copies = [
    ['content/course/manifest.json', 'manifest.json'],
    [indexPath, 'connections-index.json'],
    ...unitPaths.map((file) => [file, `units/${path.basename(file)}`]),
    ...connectionPaths.map((file) => [
      file,
      `connections/${path.basename(file)}`,
    ]),
  ];
  for (const [published, generated] of copies)
    assert.equal(
      hash(fs.readFileSync(path.join(directory, published))),
      hash(fs.readFileSync(path.join(sourceRoot, generated))),
      `Exact generated bytes: ${published}`,
    );
  const bindings = readJson(path.join(sourceRoot, 'source-bindings.json'));
  assert.equal(bindings.releaseId, manifest.releaseId);
  assert.equal(bindings.sourceHash, manifest.sourceHash);
  const checks = units
    .flatMap((unit) =>
      unit.teaching
        ? ['prediction', 'transfer', 'retry'].map(
            (phase) => unit.teaching[phase],
          )
        : [],
    )
    .concat(
      connections.flatMap((connection) =>
        ['prediction', 'transfer', 'retry'].map(
          (phase) => connection.model[phase],
        ),
      ),
    );
  assert.equal(checks.length, 303);
  assert.equal(
    new Set(checks.map((check) => check.id)).size,
    checks.length,
    'Assessment identities are globally unique',
  );
  assert.deepEqual(
    checks.map((check) => check.id).sort(),
    bindings.assessments.map((binding) => binding.productionId).sort(),
    'All packaged checks retain source-bound semantic identities',
  );
  const directlyAssessed = new Set(checks.flatMap((check) => check.conceptIds));
  assert.equal(
    directlyAssessed.size,
    448,
    'Direct scope stays separate from all explained concepts',
  );
  for (const summary of manifest.units) {
    const unit = units.find((candidate) => candidate.id === summary.id);
    assert.deepEqual(
      summary.prerequisites,
      unit.prerequisites,
      `Declared prerequisite concepts: ${summary.id}`,
    );
    assert.deepEqual(
      summary.checks,
      unit.teaching
        ? ['prediction', 'transfer', 'retry'].map((phase) => ({
            id: unit.teaching[phase].id,
            conceptIds: unit.teaching[phase].conceptIds,
          }))
        : [],
      `Named direct check scopes: ${summary.id}`,
    );
    assert.equal(
      'sections' in summary,
      false,
      'Manifest contains summaries, not eager lesson bodies',
    );
    assert.equal(
      'teaching' in summary,
      false,
      'Manifest contains scoped metadata, not eager checks',
    );
  }
  const pilotFiles = fs.readdirSync(path.join(directory, 'content/pilot'));
  assert.equal(pilotFiles.length, 1, 'One separately loaded pilot release');
  const pilotPath = `content/pilot/${pilotFiles[0]}`;
  const pilot = readJson(path.join(directory, pilotPath));
  validateRelease(pilot);
  assert.deepEqual(
    pilot,
    { ...releasePack, storage: 'static' },
    'Pilot content matches validated authored release',
  );
  assert.equal(
    pilot.storage,
    'static',
    'Pilot provenance reflects shipped delivery',
  );
  assert.equal(pilotFiles[0], `${pilot.releaseId}.json`);

  const outputFiles = walk(directory);
  for (const file of outputFiles) {
    const relative = path.relative(directory, file);
    assert.ok(
      !relative
        .split(path.sep)
        .some((part) =>
          /^(?:resources|node_modules|\.git|\.env.*|\.wrangler|backups?)$/i.test(
            part,
          ),
        ),
      `No private/infrastructure directory in output: ${relative}`,
    );
    assert.ok(
      !/\.(?:pdf|pem|key|sqlite3?|db|sql|map|ts|tsx)$/i.test(file),
      `No source, database, reference or credential artifacts: ${relative}`,
    );
    assert.ok(
      !/backup/i.test(path.basename(file)),
      `No learner backups in output: ${relative}`,
    );
  }
  const instance = await startStaticServer(directory, { base, port });
  let fetched = 0;
  try {
    const get = async (relative, status = 200) => {
      const response = await fetch(new URL(relative, instance.baseUrl));
      assert.equal(response.status, status, `${base}${relative} status`);
      fetched++;
      return response;
    };
    const loadedMainScripts = new Set();
    const inspectEntry = async (relative, collectMain) => {
      const html = await (await get(relative)).text();
      assert.match(html, /<html[^>]*lang="en"/);
      const assetUrls = [...html.matchAll(/(?:src|href)="([^"]+)"/g)]
        .map((match) => match[1])
        .filter((url) => !url.startsWith('#') && !/^https?:/.test(url));
      assert.ok(
        assetUrls.some((url) => /\.js$/.test(url)),
        `${relative} has a browser entry`,
      );
      for (const assetUrl of assetUrls) {
        const url = new URL(assetUrl, new URL(relative, instance.baseUrl));
        assert.ok(
          url.pathname.startsWith(base),
          `${relative} asset respects base: ${assetUrl}`,
        );
        const response = await fetch(url);
        assert.equal(
          response.status,
          200,
          `${relative} asset exists: ${assetUrl}`,
        );
        fetched++;
        if (collectMain && /\.js$/.test(url.pathname))
          loadedMainScripts.add(url.href);
      }
    };
    await inspectEntry('', true);
    await inspectEntry('pilot/', false);
    const visitedScripts = new Set();
    let initialJs = '';
    const pendingScripts = [...loadedMainScripts];
    while (pendingScripts.length) {
      const url = pendingScripts.pop();
      if (visitedScripts.has(url)) continue;
      visitedScripts.add(url);
      const response = await fetch(url);
      assert.equal(response.status, 200);
      const js = await response.text();
      initialJs += js;
      // Follow static imports only. Dynamic imports are deliberately lazy.
      for (const match of js.matchAll(
        /(?:\bimport\s*(?:[^;]*?\bfrom\s*)?|\bexport\s+[^;]*?\bfrom\s*)["']([^"']+\.js)["']/g,
      ))
        pendingScripts.push(new URL(match[1], url).href);
    }
    for (const check of checks)
      assert.ok(
        !initialJs.includes(check.prompt) &&
          !initialJs.includes(escape(check.prompt)),
        `Initial main bundle does not embed lesson check ${check.id}`,
      );
    for (const question of pilot.questions)
      assert.ok(
        !initialJs.includes(question.stem),
        `Initial main bundle does not embed pilot question ${question.id}`,
      );
    for (const file of [
      'content/course/manifest.json',
      indexPath,
      ...unitPaths,
      ...connectionPaths,
      pilotPath,
    ]) {
      const response = await get(file);
      assert.match(response.headers.get('content-type'), /application\/json/);
      assert.equal(
        hash(Buffer.from(await response.arrayBuffer())),
        hash(fs.readFileSync(path.join(directory, file))),
        `HTTP serves exact file: ${file}`,
      );
    }
    for (const missing of [
      'not-a-route',
      'api/course',
      'content/course/missing-release/units/missing.json',
      `${releasePath}/units/missing.json`,
      `${releasePath}/connections/missing.json`,
    ])
      await get(missing, 404);
    if (base !== '/')
      assert.equal(
        (await fetch(instance.origin + '/')).status,
        404,
        'Subpath server does not conceal wrong-base requests',
      );
    return {
      status: 'pass',
      releaseId: manifest.releaseId,
      sourceHash: manifest.sourceHash,
      base,
      units: units.length,
      connections: connections.length,
      explainedConcepts: manifest.counts.concepts,
      checks: checks.length,
      directlyAssessedConcepts: directlyAssessed.size,
      pilotReleaseId: pilot.releaseId,
      exactJsonFiles: copies.length + 1,
      outputFiles: outputFiles.length,
      httpRequests: fetched,
      initialScriptFiles: visitedScripts.size,
      note: 'Exhaustive content/schema/HTTP inventory and static dependency inspection; browser interaction and readable visual sampling are separate.',
    };
  } finally {
    await instance.close();
  }
}
if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href
) {
  const option = (name, fallback) =>
    process.argv
      .find((argument) => argument.startsWith(`--${name}=`))
      ?.slice(name.length + 3) ?? fallback;
  const result = await verifyStaticOutput({
    directory: option('directory', path.join(webRoot, 'dist')),
    base: option('base', '/'),
    expectedRelease: option('expected-release'),
    port: Number(option('port', '0')),
  });
  const output = path.resolve(
    option(
      'output',
      path.join(webRoot, 'outputs/static-qa/static-output.json'),
    ),
  );
  const historicalPaths = [
    'visual-learning-production',
    'visual-explanation-implementation',
  ].map((name) => path.resolve(webRoot, '../planning', name));
  assert.ok(
    !historicalPaths.some(
      (directory) =>
        output === directory || output.startsWith(directory + path.sep),
    ),
    'Historical acceptance reports are protected; choose a new output path.',
  );
  fs.mkdirSync(path.dirname(output), { recursive: true });
  fs.writeFileSync(output, JSON.stringify(result, null, 2) + '\n');
  console.log(JSON.stringify(result, null, 2));
}
