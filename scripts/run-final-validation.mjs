import { createHash } from 'node:crypto';
import { spawn, spawnSync } from 'node:child_process';
import { once } from 'node:events';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const webRoot = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  '..',
);
const repositoryRoot = path.dirname(webRoot);
const isolatedRoot = '/tmp/cissp-production-qa.DClS2w';
const validationBin = '/tmp/cissp-production-validation-venv/bin';
const expectedRelease = process.argv
  .find((argument) => argument.startsWith('--expected-release='))
  ?.slice('--expected-release='.length);
const planOnly = process.argv.includes('--plan');
const port = Number(
  process.argv
    .find((argument) => argument.startsWith('--port='))
    ?.slice('--port='.length) || 3101,
);

if (
  !expectedRelease ||
  !/^cissp-course-2026-09-[a-f0-9]{16}$/.test(expectedRelease)
)
  throw new Error('Pass --expected-release=cissp-course-2026-09-<16 hex>.');
if (!Number.isInteger(port) || port < 1024 || port > 64535)
  throw new Error('The QA preview port must be an integer from 1024 to 64535.');

const sourceManifest = JSON.parse(
  fs.readFileSync(path.join(webRoot, 'lib/data/course/manifest.json'), 'utf8'),
);
if (sourceManifest.releaseId !== expectedRelease)
  throw new Error(
    `Expected ${expectedRelease}, but generated bytes are ${sourceManifest.releaseId}.`,
  );

const commands = [
  {
    id: 'historical-release',
    cwd: '.',
    command: ['node', 'scripts/validate-review-release.mjs'],
  },
  { id: 'web-typecheck', cwd: 'web', command: ['npm', 'run', 'typecheck'] },
  { id: 'web-lint', cwd: 'web', command: ['npm', 'run', 'lint'] },
  {
    id: 'course-render',
    cwd: 'web',
    command: ['npm', 'run', 'course:render-check'],
  },
  { id: 'production-build', cwd: 'web', command: ['npm', 'run', 'build'] },
];

if (planOnly) {
  console.log(
    JSON.stringify(
      {
        expectedRelease,
        isolatedRoot,
        validationBin,
        port,
        commands,
        migrations: [
          'drizzle/0000_ancient_squadron_supreme.sql',
          'drizzle/0001_careful_calypso.sql',
          'drizzle/0002_flaky_winter_soldier.sql',
        ],
        releaseCoverage: [
          'npm',
          'run',
          'course:coverage',
          '--',
          `--expected-release=${expectedRelease}`,
        ],
        report: `planning/visual-learning-production/qa/${expectedRelease}-validation.json`,
      },
      null,
      2,
    ),
  );
  process.exit(0);
}

if (!fs.existsSync(path.join(validationBin, 'jsonschema')))
  throw new Error(`Missing jsonschema environment at ${validationBin}.`);

const sha256 = (value) => createHash('sha256').update(value).digest('hex');
const run = (id, command, cwd, extraEnv = {}) => {
  const startedAt = Date.now();
  const result = spawnSync(command[0], command.slice(1), {
    cwd,
    env: {
      ...process.env,
      PATH: `${validationBin}:${process.env.PATH}`,
      ...extraEnv,
    },
    encoding: 'utf8',
    maxBuffer: 32 * 1024 * 1024,
  });
  const output = `${result.stdout || ''}${result.stderr || ''}`;
  const record = {
    id,
    command: command.join(' '),
    cwd: path.relative(isolatedRoot, cwd) || '.',
    exitCode: result.status,
    durationMs: Date.now() - startedAt,
    outputSha256: sha256(output),
    outputTail: output.slice(-8_000),
    status: result.status === 0 ? 'pass' : 'fail',
  };
  if (record.status === 'fail') {
    console.error(output);
    throw Object.assign(new Error(`${id} failed.`), { record });
  }
  console.log(`${id}: pass`);
  return record;
};

fs.rmSync(isolatedRoot, { recursive: true, force: true });
fs.mkdirSync(isolatedRoot, { recursive: true });
const refresh = spawnSync(
  'rsync',
  [
    '-a',
    '--delete',
    '--exclude=.git',
    '--exclude=.DS_Store',
    '--exclude=.impeccable',
    '--exclude=resources/***',
    '--exclude=web/node_modules',
    '--exclude=web/.wrangler',
    '--exclude=web/dist',
    `${repositoryRoot}/`,
    `${isolatedRoot}/`,
  ],
  { encoding: 'utf8' },
);
if (refresh.status !== 0)
  throw new Error(`Isolated workspace refresh failed: ${refresh.stderr}`);
fs.mkdirSync(path.join(isolatedRoot, 'resources'), { recursive: true });
fs.symlinkSync(
  path.join(webRoot, 'node_modules'),
  path.join(isolatedRoot, 'web/node_modules'),
);

const baseline = JSON.parse(
  fs.readFileSync(
    path.join(
      isolatedRoot,
      'planning/visual-learning-production/source-baseline.json',
    ),
    'utf8',
  ),
);
const baselineMismatches = Object.entries(baseline).filter(
  ([file, expected]) =>
    !fs.existsSync(path.join(isolatedRoot, file)) ||
    sha256(fs.readFileSync(path.join(isolatedRoot, file))) !== expected,
);
if (baselineMismatches.length)
  throw new Error(
    `Protected historical baseline changed: ${baselineMismatches[0][0]}.`,
  );

const results = [];
try {
  for (const item of commands)
    results.push(run(item.id, item.command, path.join(isolatedRoot, item.cwd)));

  const isolatedWeb = path.join(isolatedRoot, 'web');
  const persistenceRoot = path.join(isolatedRoot, '.qa-state');
  fs.rmSync(persistenceRoot, { recursive: true, force: true });
  for (const migration of [
    'drizzle/0000_ancient_squadron_supreme.sql',
    'drizzle/0001_careful_calypso.sql',
    'drizzle/0002_flaky_winter_soldier.sql',
  ])
    results.push(
      run(
        `migration-${path.basename(migration, '.sql')}`,
        [
          'npx',
          'wrangler',
          'd1',
          'execute',
          'DB',
          '--local',
          '--config',
          'wrangler.local.json',
          '--persist-to',
          persistenceRoot,
          '--file',
          migration,
          '--yes',
        ],
        isolatedWeb,
      ),
    );

  const serverOutput = [];
  const server = spawn(
    path.join(isolatedWeb, 'node_modules/.bin/wrangler'),
    [
      'dev',
      '--config',
      'dist/server/wrangler.json',
      '--port',
      String(port),
      '--inspector-port',
      String(port + 1000),
      '--persist-to',
      persistenceRoot,
      '--show-interactive-dev-session',
      'false',
      '--log-level',
      'error',
    ],
    {
      cwd: isolatedWeb,
      env: { ...process.env, PATH: `${validationBin}:${process.env.PATH}` },
      stdio: ['ignore', 'pipe', 'pipe'],
    },
  );
  server.stdout.on('data', (chunk) => serverOutput.push(String(chunk)));
  server.stderr.on('data', (chunk) => serverOutput.push(String(chunk)));
  try {
    const deadline = Date.now() + 30_000;
    let ready = false;
    while (Date.now() < deadline) {
      try {
        const response = await fetch(`http://127.0.0.1:${port}/api/course`);
        if (response.ok) {
          ready = true;
          break;
        }
      } catch {}
      await new Promise((resolve) => setTimeout(resolve, 250));
    }
    if (!ready)
      throw new Error(
        `Production preview did not become ready. ${serverOutput.join('').slice(-4_000)}`,
      );
    results.push(
      run(
        'production-course-api',
        ['npm', 'run', 'course:api-check'],
        isolatedWeb,
        { COURSE_API_BASE_URL: `http://127.0.0.1:${port}` },
      ),
    );
  } finally {
    server.kill('SIGTERM');
    await Promise.race([
      once(server, 'exit'),
      new Promise((resolve) => setTimeout(resolve, 5_000)),
    ]);
  }

  const d1Query = run(
    'sealed-d1-coverage',
    [
      'npx',
      'wrangler',
      'd1',
      'execute',
      'DB',
      '--local',
      '--config',
      'wrangler.local.json',
      '--persist-to',
      persistenceRoot,
      '--command',
      `SELECT id,sealed,unit_count,concept_count,concept_occurrence_count,teaching_model_count,assessment_count FROM course_releases WHERE id='${expectedRelease}'; SELECT COUNT(*) AS units FROM course_units WHERE release_id='${expectedRelease}'; SELECT COUNT(*) AS bindings FROM course_source_bindings WHERE release_id='${expectedRelease}'; SELECT COUNT(*) AS connections FROM course_connections WHERE release_id='${expectedRelease}'; SELECT COUNT(*) AS reference_relationships FROM course_reference_relationships WHERE release_id='${expectedRelease}';`,
      '--json',
    ],
    isolatedWeb,
  );
  results.push(d1Query);
  const d1Text = d1Query.outputTail;
  for (const expected of [
    `"id": "${expectedRelease}"`,
    '"sealed": 1',
    '"units": 90',
    '"bindings": 892',
    '"connections": 11',
    '"reference_relationships": 21',
  ])
    if (!d1Text.includes(expected))
      throw new Error(`D1 coverage output is missing ${expected}.`);

  results.push(
    run(
      'release-coverage-artifact',
      [
        'npm',
        'run',
        'course:coverage',
        '--',
        `--expected-release=${expectedRelease}`,
      ],
      isolatedWeb,
    ),
  );
  const coverageRelativePath = path.join(
    'planning/visual-learning-production/qa',
    `${expectedRelease}-coverage.json`,
  );
  const isolatedCoveragePath = path.join(isolatedRoot, coverageRelativePath);
  const coverageBytes = fs.readFileSync(isolatedCoveragePath);
  const coverage = JSON.parse(coverageBytes);
  if (
    coverage.releaseId !== expectedRelease ||
    coverage.counts.units !== 90 ||
    coverage.counts.distinctConcepts !== 698 ||
    coverage.counts.conceptOccurrences !== 892 ||
    coverage.counts.authoredTeachingModels !== 101 ||
    coverage.counts.productionChecks !== 303 ||
    coverage.counts.adjudicatedTreatmentDecisions !== 79
  )
    throw new Error('Release coverage artifact has an unexpected denominator.');
  const liveCoveragePath = path.join(repositoryRoot, coverageRelativePath);
  fs.mkdirSync(path.dirname(liveCoveragePath), { recursive: true });
  fs.copyFileSync(isolatedCoveragePath, liveCoveragePath);

  const historicalResult = fs.readFileSync(
    path.join(isolatedRoot, 'knowledge/quality/validation-results.json'),
  );
  const report = {
    schemaVersion: 1,
    releaseId: sourceManifest.releaseId,
    sourceHash: sourceManifest.sourceHash,
    checkedAt: new Date().toISOString(),
    isolatedRoot,
    status: 'pass',
    protectedHistoricalFiles: {
      expected: Object.keys(baseline).length,
      matching: Object.keys(baseline).length,
      mismatches: 0,
    },
    historicalValidationResultSha256: sha256(historicalResult),
    coverageArtifact: {
      path: coverageRelativePath.split(path.sep).join('/'),
      sha256: sha256(coverageBytes),
      reviewBindingStatus: coverage.reviewBinding.status,
      currentSourceMatchesRelease:
        coverage.reviewBinding.currentSourceMatchesRelease,
    },
    productionPreview: {
      port,
      freshPersistence: true,
      migrations: 3,
      apiVerified: true,
    },
    results,
  };
  const reportPath = path.join(
    repositoryRoot,
    'planning/visual-learning-production/qa',
    `${expectedRelease}-validation.json`,
  );
  fs.mkdirSync(path.dirname(reportPath), { recursive: true });
  fs.writeFileSync(reportPath, `${JSON.stringify(report, null, 2)}\n`);
  console.log(
    JSON.stringify(
      { status: 'pass', releaseId: expectedRelease, reportPath },
      null,
      2,
    ),
  );
} catch (error) {
  if (error.record) results.push(error.record);
  throw error;
}
